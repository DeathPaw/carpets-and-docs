package ru.carpet.model;

/**
 * Статусы экземпляра услуги в позиции заказа.
 */
public enum ServiceStatus {
    /** Создано — услуга назначена, исполнитель ещё не приступил */
    CREATED,
    /** В работе — исполнитель выполняет услугу */
    IN_PROGRESS,
    /** Готово — услуга выполнена */
    DONE,
    /** Отменено */
    CANCELLED
}
