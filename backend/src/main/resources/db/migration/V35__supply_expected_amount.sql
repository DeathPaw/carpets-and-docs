-- V35: ожидаемая цена в заявке на закупку.
--
-- Оператор часто знает стоимость заранее — на этапе согласования или заказа.
-- Раньше сумму можно было ввести только в момент получения, и до этого заявка
-- не давала понять, во что обойдётся закупка.
--
-- expected_amount — план, actual_amount — факт. В расходы по-прежнему уходит
-- только факт; план нужен для планирования и подставляется в окно получения.

ALTER TABLE supply_requests ADD COLUMN IF NOT EXISTS expected_amount NUMERIC(12,2);

COMMENT ON COLUMN supply_requests.expected_amount IS
    'Ожидаемая стоимость закупки. В расходы не попадает — только actual_amount.';
