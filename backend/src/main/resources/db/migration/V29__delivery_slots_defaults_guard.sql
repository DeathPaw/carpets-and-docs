-- V29: страховка дефолтных слотов доставки (правка №4).
--
-- Зачем отдельная миграция, если сид уже есть в V18:
--   • V18 применялась на БД, где слоты могли быть удалены руками до появления
--     админки в Справочниках — тогда день остаётся без рабочего времени, и
--     Логистика показывает его как выходной. Здесь мы это чиним.
--   • База, поднятая до V18 из дампа, могла вообще не получить сид.
--
-- Идемпотентность: вставляем слот дня ТОЛЬКО если у этого дня нет ни одного
-- слота вообще. Если админ настроил свои интервалы (или осознанно сделал день
-- выходным, оставив хотя бы один выключенный слот) — не трогаем.
--
-- Дефолт по договорённости с оператором:
--   Пн-Пт 17:00-20:30 «Вечер»   — рабочее время развозки в будни;
--   Сб    10:00-20:30 «Весь день» — в выходной график шире;
--   Вс    без слотов             — выходной, намеренно ничего не создаём.
-- «Без слота» отдельной строкой не заводим: это не слот, а состояние
-- «время не назначено», оно всегда доступно как зона на доске логистики.

INSERT INTO delivery_time_slots (day_of_week, start_time, end_time, label, sort_order)
SELECT d.dow, d.st::time, d.et::time, d.lbl, 1
  FROM (VALUES
        (1, '17:00', '20:30', 'Вечер'),
        (2, '17:00', '20:30', 'Вечер'),
        (3, '17:00', '20:30', 'Вечер'),
        (4, '17:00', '20:30', 'Вечер'),
        (5, '17:00', '20:30', 'Вечер'),
        (6, '10:00', '20:30', 'Весь день')
       ) AS d(dow, st, et, lbl)
 WHERE NOT EXISTS (
        SELECT 1 FROM delivery_time_slots s WHERE s.day_of_week = d.dow
      );
