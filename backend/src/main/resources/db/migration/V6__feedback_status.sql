-- ============================================================================
-- V6: Статусы обращений.
-- Раньше у обращения был только delete; теперь нужно вести жизненный цикл —
-- какие посмотрели, какие в работе, какие закрыты и т.п.
-- Хранится как VARCHAR (без ENUM) — добавление нового статуса не требует миграции.
-- ============================================================================

ALTER TABLE feedback_messages
    ADD COLUMN IF NOT EXISTS status VARCHAR(40) NOT NULL DEFAULT 'NEW';

-- Возможные значения (управляются на фронте через FEEDBACK_STATUS_LABELS):
--   NEW           — только что создано, ещё не просмотрено
--   REVIEWED      — рассмотрено
--   IN_PROGRESS   — взято в работу
--   DONE          — реализовано
--   REJECTED      — отказано
--   NEED_INFO     — требуется пояснение от автора
CREATE INDEX IF NOT EXISTS idx_feedback_status ON feedback_messages(status);
