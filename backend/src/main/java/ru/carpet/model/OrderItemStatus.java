package ru.carpet.model;

/**
 * Статусы позиции заказа.
 * Вычисляются автоматически на основе статусов услуг позиции.
 */
public enum OrderItemStatus {
    /** Создано — позиция добавлена, работы не начаты */
    CREATED,
    /** Взято в работу — хотя бы одна услуга в работе */
    IN_PROGRESS,
    /** Частично готово — хотя бы одна услуга готова, но не все */
    PARTIALLY_DONE,
    /** Готово — все услуги выполнены */
    DONE,
    /** Отменено */
    CANCELLED
}
