/**
 * Активные сценарии-челленджи для тренажёра.
 *
 * <p>Чем это отличается от Joyride-тура? Joyride — пассивная подсветка
 * («это раздел заказы, нажмите далее»). Челлендж даёт ЗАДАЧУ — оператор
 * сам нажимает кнопки, переходит по страницам, заполняет формы; панель
 * автоматически отмечает шаги, когда оператор реально выполняет действие
 * (через интерсептор API в client.ts).
 *
 * <p>Сценариев пока три (Спринт E). Добавлять новые — просто допишите объект
 * в массив. Тип `Trigger` описывает, как панель понимает, что шаг выполнен:
 *
 *   • `route` — оператор перешёл на нужный pathname.
 *   • `api` — успешно прошёл API-запрос (метод+URL, опциональный predicate
 *     по телу запроса/ответа для случаев типа «PATCH status, но именно DONE»).
 *   • `manual` — нет автоматической проверки, оператор сам кликает «Готово»
 *     в панели (нужен для шагов «посмотрите на это»).
 */

export type Trigger =
    | { type: 'route'; pathname: string | RegExp }
    | {
          type: 'api'
          method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'
          urlPattern: RegExp
          /** Доп. проверка по телу запроса/ответа. Возвращает true — шаг считается выполненным. */
          predicate?: (req: unknown, res: unknown) => boolean
      }
    | { type: 'manual' }

export interface ChallengeStep {
    /** Короткий заголовок шага — отображается в списке слева. */
    title: string
    /** Развёрнутая подсказка под заголовком текущего шага. */
    hint: string
    /** Условие, по которому панель отметит шаг выполненным. */
    trigger: Trigger
}

export interface ChallengeScenario {
    id: string
    title: string
    description: string
    steps: ChallengeStep[]
}

/**
 * Безопасно достаёт ключ из произвольного тела запроса/ответа. axios отдаёт
 * нам тело как `unknown`, поэтому используем тип-гард, а не cast в any.
 */
function pick(obj: unknown, key: string): unknown {
    if (obj && typeof obj === 'object' && key in obj) {
        return (obj as Record<string, unknown>)[key]
    }
    return undefined
}

