package ru.carpet.model;

/**
 * Статусы заказа.
 * Переходы LEAD и DELIVERED управляются только вручную через API.
 */
public enum OrderStatus {
    /** Лид — первичное обращение клиента */
    LEAD,
    /** Создано — заказ принят в работу */
    CREATED,
    /** На забор — заказ готов к забору */
    FOR_PICKUP,
    /** Взято в работу */
    IN_PROGRESS,
    /** Частично готово — хотя бы одна позиция готова */
    PARTIALLY_DONE,
    /** Готово — все позиции выполнены */
    DONE,
    /** Доставлено клиенту */
    DELIVERED,
    /**
     * Частично доставлено (Спринт V9 / фидбэк Миши 11 мая): водитель отметил
     * часть позиций как DELIVERED, а минимум одну — как LOST. Заказ висит в
     * этом статусе до решения оператора: создать гарантию (повторно сделать
     * и довезти бесплатно), списать, согласовать с клиентом другую компенсацию.
     */
    PARTIALLY_DELIVERED,
    /** Завершён — оплачен и закрыт. Финальный статус, изменения и отмена запрещены. */
    COMPLETED,
    /** Отменен */
    CANCELLED
}
