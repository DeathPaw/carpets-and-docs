package ru.carpet.model;

/**
 * Статусы заказа.
 * Переходы LEAD и DELIVERED управляются только вручную через API.
 */
public enum OrderStatus {
    /** Лид — первичное обращение клиента */
    LEAD,
    /** Создано — заказ принят в работу */
    CREATED,
    /** На забор — заказ готов к забору */
    FOR_PICKUP,
    /** Взято в работу */
    IN_PROGRESS,
    /** Частично готово — хотя бы одна позиция готова */
    PARTIALLY_DONE,
    /** Готово — все позиции выполнены */
    DONE,
    /** Доставлено клиенту */
    DELIVERED,
    /** Завершён — оплачен и закрыт. Финальный статус, изменения и отмена запрещены. */
    COMPLETED,
    /** Отменен */
    CANCELLED
}
