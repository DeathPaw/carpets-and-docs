-- V43: подтверждение клиента по забору/отвозу (правка №1 от 17.09).
--
-- Оператор обзванивает клиентов накануне выезда, но отметить «этот уже
-- подтвердил» было негде: признак держали в голове или в чужих табличках.
-- Это НЕ статус заказа, а операционный флажок логистики: «Уточнить» (FALSE)
-- или «Подтверждён» (TRUE). С клиентами работают несколько операторов,
-- поэтому храним, кто именно поставил подтверждение и когда.
--
-- Флажок сбрасывается в «Уточнить» при переносе даты забора/отвоза и после
-- того, как ковры забрали: дальше клиента надо обзванивать заново — уже про
-- доставку готовых ковров.

ALTER TABLE orders ADD COLUMN IF NOT EXISTS client_confirmed    BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS client_confirmed_by VARCHAR(150);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS client_confirmed_at TIMESTAMP;
