-- V52: точность долей за ковёр (ТЗ v2, приёмочный тест AT01).
--
-- Доли хранились как NUMERIC(5,2), и «поровну на троих» давало 33.33 + 33.33
-- + 33.34. Сдельщик за ковёр 3 м² по 300 ₽/м² получал 299,97 ₽ вместо ровно
-- 300 ₽, а по ТЗ должно выходить 300. Пяти знаков после запятой достаточно:
-- 33.33333 % от 900 ₽ округляется до копеек ровно в 300,00 ₽.

ALTER TABLE order_item_shares        ALTER COLUMN percent TYPE NUMERIC(8,5);
ALTER TABLE payroll_share_rule_members ALTER COLUMN percent TYPE NUMERIC(8,5);
