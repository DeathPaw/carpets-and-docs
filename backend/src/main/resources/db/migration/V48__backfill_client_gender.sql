-- V48: разовое предзаполнение пола у уже заведённых клиентов (правка №1 от 13.09).
--
-- Поле появилось в V47 и заполняется при создании клиента. Но в базе уже
-- сотни карточек, и без этого шага портрет базы по полу был бы пустым.
--
-- Берём только отчество — признак почти стопроцентный. Имена вроде «Саша»
-- или нерусские оставляем пустыми: пусто честнее неверного, оператор
-- поправит в карточке.

UPDATE clients
   SET gender = CASE
        WHEN name ~ '(вна|чна)$' THEN 'FEMALE'
        WHEN name ~ '(вич|ьич)$' THEN 'MALE'
        ELSE NULL
       END
 WHERE gender IS NULL
   AND client_type <> 'LEGAL_ENTITY';
