-- V32: справочник баннеров «Обновления».
--
-- Оператор жмёт кнопку «Обновления» рядом с «Что делать?» и видит список
-- сообщений: что починили, что появилось нового. Раньше такие вещи приходилось
-- рассказывать голосом — теперь это настраиваемый справочник, и релизные заметки
-- можно добавлять без правки кода.
--
-- Даты показа: баннер виден, если сегодня попадает в интервал [starts_on, ends_on].
-- NULL с любой стороны = граница не задана (показывать бессрочно в эту сторону).

CREATE TABLE IF NOT EXISTS update_banners (
    id          BIGSERIAL PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    body        TEXT         NOT NULL,
    /** Показывать начиная с этой даты. NULL — с самого начала. */
    starts_on   DATE,
    /** Показывать по эту дату включительно. NULL — бессрочно. */
    ends_on     DATE,
    /** Порядок в списке: меньше — выше. */
    sort_order  INT          NOT NULL DEFAULT 0,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT update_banners_dates_chk CHECK (ends_on IS NULL OR starts_on IS NULL OR ends_on >= starts_on)
);

-- Индекс под основной запрос попапа: активные баннеры, попадающие в сегодня.
CREATE INDEX IF NOT EXISTS idx_update_banners_active
    ON update_banners (starts_on, ends_on) WHERE is_active = TRUE;

