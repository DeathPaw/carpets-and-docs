-- V37: признак «услуге нужен исполнитель».
--
-- Смена статуса услуги на «В работе»/«Готова» требовала назначенного сотрудника
-- всегда. Для самовывоза это бессмысленно: вещи везёт сам клиент, наш сотрудник
-- в этом не участвует — но статус услуги без «исполнителя» было не сдвинуть,
-- и оператор упирался в ошибку на пустом месте.
--
-- Флаг, а не проверка имени: набор таких услуг будет расти (выдача в офисе,
-- отказ клиента), и решать это должен справочник, а не строковое сравнение.

ALTER TABLE skus ADD COLUMN IF NOT EXISTS requires_assignee BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN skus.requires_assignee IS
    'Нужен ли назначенный сотрудник для перевода услуги в работу/готово. FALSE — например, самовывоз.';

UPDATE skus SET requires_assignee = FALSE WHERE name ILIKE '%самовывоз%';
