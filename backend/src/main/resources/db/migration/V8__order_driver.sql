-- V8: Назначенный водитель/логист на заказ (Спринт D, фидбэк пользователя 11 мая).
--
-- Проблема: в логистике оператор перетаскивает карточки по дням, но кому
-- конкретно везти — не указывает. Раньше это решалось через assignees услуги
-- «Доставка» (т.е. сотрудник назначался на услугу). Это давало кучу побочной
-- работы UI: найти позицию доставки → найти её услугу → назначить.
--
-- Решение: храним водителя прямо на заказе — orders.assigned_driver_id.
-- Один заказ — один водитель (если заказ распадается на разные доставки,
-- придётся делить на дочерние; пока этой задачи нет).
--
-- ON DELETE SET NULL: увольнение сотрудника не удаляет заказы, просто снимает
-- с них привязку. Хотя active=false мы уже используем — для совместимости.
-- ============================================================================

ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS assigned_driver_id BIGINT
    REFERENCES employees(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_orders_assigned_driver
    ON orders(assigned_driver_id)
    WHERE assigned_driver_id IS NOT NULL;
