-- V39: реквизиты для печатных форм (правка №6 от 09.09).
--
-- Шапка документов меняется: основной посыл — бренд «Коврокот» как направление
-- прачечной «Возрождение». Реквизиты храним в одном месте, чтобы при смене
-- телефона или адреса они сразу обновлялись во всех печатных формах: накладных
-- на приём и выдачу, пустых бланках, маршрутном листе. Правятся в Справочниках.
--
-- ИНН, ОГРНИП, расчётный счёт и банковские реквизиты заказчик просил НЕ печатать,
-- поэтому для них и полей нет.
--
-- Таблица из одной строки: CHECK (id = 1) не даёт завести вторую «версию»
-- реквизитов, из которой печать взяла бы не ту.

CREATE TABLE IF NOT EXISTS company_settings (
    id              SMALLINT     PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    /** Крупная строка шапки — «Коврокот». */
    brand_name      VARCHAR(100) NOT NULL,
    /** «стирка ковров с забором и доставкой». */
    tagline         VARCHAR(255),
    /** «направление прачечной «Возрождение»». */
    subtitle        VARCHAR(255),
    /** Адрес в шапке, короткой формой. */
    header_address  VARCHAR(255),
    /** Исполнитель в реквизитах: «ИП Кузнецов А.Г.». */
    executor        VARCHAR(255),
    /** Адрес в реквизитах, полной формой. */
    legal_address   VARCHAR(255),
    /** Телефоны одной строкой через запятую — печатаются как есть. */
    phones          VARCHAR(255),
    /** Логотип data-URL'ом (data:image/png;base64,…). NULL — шапка без логотипа:
     *  файл заказчик передаст отдельно и загрузит сам. */
    logo_data       TEXT,
    updated_at      TIMESTAMP    NOT NULL DEFAULT NOW()
);

