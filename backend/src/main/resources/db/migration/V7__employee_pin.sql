-- ============================================================================
-- V7: PIN-авторизация работников (Спринт D, замечание Миши 11 мая).
--
-- Сценарий: рабочий на производстве/водитель открывает мобилку, выбирает свою
-- плитку, вводит 4 цифры — попадает в свой личный кабинет «мои услуги на сегодня».
-- Без классического логин/пароль — у людей с 9 классами школы это не работает.
--
-- Хранение:
--   • employees.pin — VARCHAR(10) NULL. NULL означает «вход не настроен» —
--     сотрудник пока не может авторизоваться. Супервизор задаёт PIN из карточки
--     сотрудника. При первом входе работник может сам задать (если NULL).
--   • Длина = 10 чтобы оставить запас, но фактически используем 4 цифры.
--   • БЕЗ хеширования — это локальная производственная система, не публичная;
--     PIN'ы существуют только для разделения личных кабинетов на одном моноблоке,
--     не для криптографической защиты. Если поднимем на белый IP — будем хешировать.
-- ============================================================================

ALTER TABLE employees ADD COLUMN IF NOT EXISTS pin VARCHAR(10);

-- Индекс для быстрого поиска employee по PIN при логине. Не уникальный — теоретически
-- два работника могут случайно выбрать один PIN (мы это разрулим UI'ом, но FK не нужен).
CREATE INDEX IF NOT EXISTS idx_employees_pin ON employees(pin);
