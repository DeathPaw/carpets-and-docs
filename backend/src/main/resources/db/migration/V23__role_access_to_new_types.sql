-- V23: открыть роли «Водитель» доступ к типу «Приём».
--
-- После V22 «Приём» — отдельный item_type. Назначение исполнителя на услугу
-- проверяется через employee_role_item_types (role.id → item_type.id).
-- Без записи водителя нельзя выбрать в селекторе исполнителей для услуги «Приём».
--
-- Водитель забирает вещи у клиента → принимает их → отдаёт на стирку.
-- Поэтому ему открываем тип «Приём» (так же как уже открыт «Доставка» в V12).
--
-- ⚠ «Оформление» — НЕ даём водителю. Это оформление заказа в системе, делается
-- оператором или админом, не водителем. На уровне БД роли employee_roles
-- для типа «Оформление» вообще не привязаны: автоназначение оператора-создателя
-- работает напрямую через users.role, минуя employee_role_item_types.

INSERT INTO employee_role_item_types (role_id, item_type_id)
SELECT er.id, it.id
  FROM employee_roles er, item_types it
 WHERE er.name = 'Водитель'
   AND it.name = 'Приём'
ON CONFLICT DO NOTHING;
