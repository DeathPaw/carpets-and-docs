-- V42: дата прайса заказа — историческая цена.
--
-- Проблема: цены услуг всегда считались по ТЕКУЩЕМУ прайсу (skus.price), хотя
-- версии прайса уже писались в sku_versions. Из-за этого любое касание позиции
-- в старом заказе (перемер, смена типа позиции туда и обратно) пересчитывало
-- его по новой цене: клиенту называли 100 ₽/м², а после подорожания заказ
-- внезапно становился дороже.
--
-- Теперь у заказа есть дата прайса. Все автоматические расчёты берут ту версию
-- услуги, которая действовала на эту дату. По умолчанию — день оформления
-- заказа; оператор может осознанно перевести заказ на текущий прайс
-- (кнопка «Пересчитать по текущему прайсу» — она и двигает эту дату).

ALTER TABLE orders ADD COLUMN IF NOT EXISTS price_date DATE;

-- Старым заказам — день их создания: именно по тому прайсу их и считали.
UPDATE orders SET price_date = created_at::date WHERE price_date IS NULL;

ALTER TABLE orders ALTER COLUMN price_date SET DEFAULT CURRENT_DATE;
ALTER TABLE orders ALTER COLUMN price_date SET NOT NULL;
