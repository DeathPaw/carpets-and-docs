-- V58: исходная цена позиции гарантийного заказа (ПР-017).
--
-- Гарантийный заказ для клиента бесплатный: цены услуг и позиций обнуляются.
-- Но для аналитики и проверки истории нужно знать, сколько эти ковры стоили
-- в обычном заказе. Пишем сюда цену позиции до обнуления (при создании гарантии
-- из исходного заказа — цену исходной позиции). NULL — позиция не гарантийная
-- или стоила 0.
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS warranty_original_price NUMERIC(12,2);
